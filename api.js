'use strict';

const Homey = require('homey');

/**
 * API route handlers for the Homey AAOS Companion app.
 *
 * These functions are mapped to the routes declared in `.homeycompose/app.json`:
 *
 *  - `POST /auth/start`  → {@link startAuth}
 *  - `GET  /auth/poll`   → {@link pollAuth}
 *
 * Both routes are declared with `"public": true` so any device can call them without
 * a Homey Web API bearer token. This is intentional: the AAOS app does not yet have
 * a Homey token when it initiates the authentication flow.
 *
 * The only security mechanism protecting these endpoints is the `sessionId`, which is
 * a 64-character hex string generated with `SecureRandom` (256-bit entropy) by the
 * AAOS app. The token is delivered exactly once and is deleted immediately after retrieval.
 *
 */

/** @constant {RegExp} SESSION_ID_REGEX - Strict validation pattern for AAOS session IDs (64 hexadecimal characters). */
const SESSION_ID_REGEX = /^[0-9a-fA-F]{64}$/;

const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Default device classes considered valid environmental/climate temperature sources.
 * @constant {string[]}
 */
const DEFAULT_CLIMATE_CLASSES = ['sensor', 'thermostat', 'heater', 'airconditioning'];

/**
 * Retrieves the set of device classes allowed for climate temperature readings.
 * Uses environment variable `CLIMATE_DEVICE_CLASSES` (comma-separated) if defined in env.json,
 * falling back to {@link DEFAULT_CLIMATE_CLASSES}.
 *
 * @private
 * @returns {Set<string>} Set of lowercase allowed class names.
 * @example
 * const classes = _getAllowedClimateClasses();
 * if (classes.has('sensor')) {
 *   // Valid climate device
 * }
 */
function _getAllowedClimateClasses() {
  const envClasses = Homey.env?.CLIMATE_DEVICE_CLASSES || process.env?.CLIMATE_DEVICE_CLASSES;
  if (typeof envClasses === 'string' && envClasses.trim().length > 0) {
    const parsed = envClasses
      .split(',')
      .map((c) => c.trim().toLowerCase())
      .filter(Boolean);
    if (parsed.length > 0) {
      return new Set(parsed);
    }
  }
  return new Set(DEFAULT_CLIMATE_CLASSES);
}

/**
 * Handles `POST /auth/start`.
 *
 * Validates the incoming payload, delegates to `app.startAuthSession()` and returns
 * the authorization URL to be displayed as a QR code on the AAOS screen.
 *
 * @public
 * @param {object} args - Request arguments provided by the Homey runtime.
 * @param {import('homey').Homey} args.homey - The Homey instance, providing access to `homey.app`.
 * @param {object} args.body - The parsed JSON request body.
 * @param {string} args.body.sessionId - A 64-char hex session identifier generated by the AAOS app (mandatory).
 * @returns {Promise<{authUrl: string}>} The authorization URL to render as a QR code.
 * @throws {Error} If sessionId is missing, invalid, or if rate limits are exceeded (HTTP 400 or 429).
 * @example
 * // Request:
 * // POST https://{homeyId}.connect.athom.com/api/app/com.dimapp.aaos/auth/start
 * // Content-Type: application/json
 * // { "sessionId": "a1b2c3d4..." }
 * //
 * // Response:
 * // { "authUrl": "https://api.athom.com/oauth2/authorise?...&redirect_uri=https://callback.athom.com/..." }
 */
async function startAuth({ homey, body }) {
  const { sessionId } = body ?? {};

  if (!sessionId || typeof sessionId !== 'string' || !SESSION_ID_REGEX.test(sessionId.trim())) {
    homey.app.error('[api:startAuth] Security rejection: Invalid or missing sessionId format. Expected 64 hex characters.');
    throw Object.assign(new Error('Missing or invalid sessionId. Must be a 64-character hexadecimal string.'), { statusCode: 400 });
  }

  return homey.app.startAuthSession(sessionId.trim());
}

/**
 * Handles `GET /auth/poll`.
 *
 * Returns the current status of an auth session. When the user has authorized the app,
 * the token is included in the response and the session is immediately deleted from memory.
 *
 * @public
 * @param {object} args - Request arguments provided by the Homey runtime.
 * @param {import('homey').Homey} args.homey - The Homey instance.
 * @param {object} args.query - The parsed query string parameters.
 * @param {string} args.query.session - The 64-char hex session identifier to poll (mandatory).
 * @returns {{ status: 'pending'|'complete'|'expired', token?: object }} Current session state.
 * @throws {Error} If session query parameter is missing or does not match 64 hex characters (HTTP 400).
 * @example
 * // Request:
 * // GET https://{homeyId}.connect.athom.com/api/app/com.dimapp.aaos/auth/poll?session=a1b2c3...
 * //
 * // Response (pending):
 * // { "status": "pending" }
 * //
 * // Response (complete — one-time only):
 * // { "status": "complete", "token": { "access_token": "...", "refresh_token": "...", "expires_in": 3600 } }
 * //
 * // Response (expired or unknown):
 * // { "status": "expired" }
 */
function pollAuth({ homey, query }) {
  const sessionId = query?.session;

  if (!sessionId || typeof sessionId !== 'string' || !SESSION_ID_REGEX.test(sessionId.trim())) {
    homey.app.error('[api:pollAuth] Security rejection: Invalid or missing session query parameter. Expected 64 hex characters.');
    throw Object.assign(new Error('Missing or invalid required query parameter: session. Must be a 64-character hexadecimal string.'), { statusCode: 400 });
  }

  return homey.app.pollAuthSession(sessionId.trim());
}

/**
 * Handles `POST /auth/refresh`.
 *
 * Verifies the provided athom_refresh_token by querying Athom Cloud.
 * If valid, generates a new owner API token and returns it along with the new refresh token.
 *
 * @public
 * @param {object} args - Request arguments provided by the Homey runtime.
 * @param {import('homey').Homey} args.homey - The Homey instance.
 * @param {object} args.body - The parsed JSON request body.
 * @param {string} args.body.athom_refresh_token - The Athom Cloud OAuth2 refresh token (mandatory).
 * @returns {Promise<{session_token: string, athom_refresh_token: string}>} The new tokens.
 * @throws {Error} If athom_refresh_token is missing, invalid, or rate limits are exceeded (HTTP 400 or 429).
 */
async function refreshAuth({ homey, body }) {
  const athomRefreshToken = body?.athom_refresh_token;

  if (!athomRefreshToken || typeof athomRefreshToken !== 'string' || athomRefreshToken.trim().length === 0 || athomRefreshToken.length > 2048) {
    homey.app.error('[api:refreshAuth] Security rejection: Missing or invalid athom_refresh_token parameter.');
    throw Object.assign(new Error('Missing or invalid athom_refresh_token.'), { statusCode: 400 });
  }

  return homey.app.refreshAuthSession(athomRefreshToken.trim());
}

/**
 * Handles `GET /dashboards`.
 *
 * Enforces session token authorization and returns a virtual dashboard containing
 * the user-selected home devices.
 *
 * @public
 * @async
 * @param {object} args - Request arguments provided by Homey Web API.
 * @param {import('homey').Homey} args.homey - The Homey application instance.
 * @returns {Promise<object>} The virtual dashboard object.
 * @throws {Error} If the request is unauthenticated or unauthorized (HTTP 401).
 * @example
 * // GET /api/app/com.dimapp.aaos/dashboards?token=<sessionToken>
 */
async function getDashboards(args) {
  const { homey } = args;
  await homey.app.requireValidSessionToken(args);
  homey.app.log('[api:getDashboards] Request received');
  
  const selectedIds = homey.settings.get('home_devices_ids') || [];
  
  // If no devices are selected, return an empty list or a flag indicating fallback is needed.
  // The Android app will handle the fallback to Favorites.
  if (selectedIds.length === 0) {
    homey.app.log('[api:getDashboards] No devices selected in settings, returning empty virtual dashboard.');
    return {};
  }

  // Create a "Virtual Dashboard" that mirrors the structure HomeyRepository.kt expects
  // Key: dashboard ID, Value: Dashboard object
  const virtualDashboardId = 'virtual-aaos-home';
  const dashboard = {
    id: virtualDashboardId,
    columns: [
      {
        widgets: [
          {
            type: 'devices_custom',
            data: {
              deviceIds: selectedIds
            }
          }
        ]
      }
    ]
  };

  const response = {};
  response[virtualDashboardId] = dashboard;

  homey.app.log(`[api:getDashboards] Returning 1 virtual dashboard with ${selectedIds.length} devices.`);
  return response;
}

/**
 * Proxy for getting all lights and locks.
 * Used by the settings page.
 */
async function getDevices({ homey }) {
  homey.app.log('[api:getDevices] Proxy request received');
  
  const localUrl = await homey.api.getLocalUrl();
  const token = await homey.api.getOwnerApiToken();
  
  const response = await fetch(`${localUrl}/api/manager/devices/device`, {
    headers: { 'Authorization': `Bearer ${token}` }
  });
  
  if (!response.ok) {
    const errorBody = await response.text().catch(() => 'no body');
    homey.app.error(`[api:getDevices] Proxy failed with status: ${response.status}. Details: ${errorBody}`);
    throw new Error(`Local API fetch failed with status: ${response.status}`);
  }
  
  const devices = await response.json();
  const totalCount = Object.keys(devices).length;

  // Find IDs of devices that are part of a group
  const excludedIds = new Set();
  for (const device of Object.values(devices)) {
    if (device.settings && Array.isArray(device.settings.deviceIds)) {
      for (const childId of device.settings.deviceIds) {
        excludedIds.add(childId);
      }
    }
  }

  const filtered = {};
  let acceptedLights = 0;
  let acceptedDoors = 0;
  let excludedHidden = 0;
  let excludedGroupMembers = 0;
  const excludedByClass = {};
  const excludedControllables = [];

  for (const [id, device] of Object.entries(devices)) {
    // 1. Skip hidden devices
    if (device.hidden === true) {
      excludedHidden++;
      if (typeof homey.app.debugLog === 'function') {
        homey.app.debugLog('api:getDevices', `REJECT '${device.name}' (reason: hidden)`);
      }
      continue;
    }

    // 2. Skip devices that are members of a group
    if (excludedIds.has(id)) {
      excludedGroupMembers++;
      if (typeof homey.app.debugLog === 'function') {
        homey.app.debugLog('api:getDevices', `REJECT '${device.name}' (reason: group member)`);
      }
      continue;
    }

    // 3. Use virtualClass override if present, otherwise fallback to driver class
    const effectiveClass = device.virtualClass || device.class;

    const isLight = effectiveClass === 'light';
    const isDoor  = effectiveClass === 'lock' || effectiveClass === 'garagedoor' || effectiveClass === 'doorbell';

    if (isLight || isDoor) {
      if (isLight) {
        acceptedLights++;
      } else {
        acceptedDoors++;
      }
      if (typeof homey.app.debugLog === 'function') {
        homey.app.debugLog('api:getDevices', `ACCEPT '${device.name}' (class=${effectiveClass}, zone=${device.zone})`);
      }
      filtered[id] = {
        id: device.id,
        name: device.name,
        class: effectiveClass,
        zone: device.zone
      };
    } else {
      const clsKey = effectiveClass || 'unknown';
      excludedByClass[clsKey] = (excludedByClass[clsKey] || 0) + 1;

      // Detect if this non-light device is controllable via onoff or dim (e.g. smart plug / relay used for lights)
      const caps = Array.isArray(device.capabilities)
        ? device.capabilities
        : Object.keys(device.capabilitiesObj || {});
      const hasToggleCapability = caps.includes('onoff') || caps.includes('dim');

      if (hasToggleCapability) {
        excludedControllables.push({
          name: device.name,
          class: device.class || 'unknown',
          virtualClass: device.virtualClass || null,
        });
      }

      if (typeof homey.app.debugLog === 'function') {
        homey.app.debugLog(
          'api:getDevices',
          `REJECT '${device.name}' (reason: unsupported class '${clsKey}', driverClass='${device.class || 'unknown'}', virtualClass='${device.virtualClass || 'none'}', capabilities=${caps.join(',')})`
        );
      }
    }
  }

  const acceptedTotal = Object.keys(filtered).length;
  const excludedTotal = totalCount - acceptedTotal;

  // Format sorted breakdown of excluded classes for concise summary
  const classBreakdown = Object.entries(excludedByClass)
    .sort((a, b) => b[1] - a[1])
    .map(([cls, cnt]) => `${cls}=${cnt}`)
    .join(', ');

  homey.app.log(
    `[api:getDevices] Scanned ${totalCount} devices: ${acceptedTotal} accepted (${acceptedLights} lights, ${acceptedDoors} doors), ${excludedTotal} excluded (classes: ${classBreakdown || 'none'}; group members: ${excludedGroupMembers}; hidden: ${excludedHidden}).`
  );

  // If devices with toggle capabilities were excluded, output a clear diagnostic hint in stdout
  if (excludedControllables.length > 0) {
    const previewList = excludedControllables
      .slice(0, 8)
      .map(d => `'${d.name}' [class: ${d.class}, virtualClass: ${d.virtualClass || 'none'}]`)
      .join(', ');
    const remainingCount = excludedControllables.length - 8;
    const remainingSuffix = remainingCount > 0 ? ` (+${remainingCount} more)` : '';

    homey.app.log(
      `[api:getDevices] Notice: ${excludedControllables.length} devices with onoff/dim capability excluded due to class: ${previewList}${remainingSuffix}. Configure 'What is plugged in' to 'Light' in Homey device settings to include them.`
    );
  }

  return filtered;
}

