/**
 * Handles `POST /geofence/event`.
 *
 * Enforces session token authorization, receives vehicle arrival or departure geofence notifications
 * from Android Automotive, and fires the appropriate Homey Flow trigger card ('geofence_enter' or 'geofence_exit').
 *
 * @public
 * @async
 * @param {object} args - Request arguments provided by Homey Web API.
 * @param {import('homey').Homey} args.homey - The Homey application instance.
 * @param {object} args.body - Request payload containing transition.
 * @param {'enter'|'exit'} args.body.transition - The transition type detected by the vehicle.
 * @returns {Promise<{success: boolean, triggered: string}>} Result of the flow trigger operation.
 * @throws {Error} If unauthorized (HTTP 401), invalid transition (HTTP 400), or trigger fails (HTTP 500).
 * @example
 * // Request:
 * // POST https://{homeyId}.connect.athom.com/api/app/com.dimapp.aaos/geofence/event?token=<sessionToken>
 * // Body: { "transition": "enter" }
 * //
 * // Response:
 * // { "success": true, "triggered": "geofence_enter" }
 */
async function postGeofenceEvent(args) {
  const { homey, body } = args;
  await homey.app.requireValidSessionToken(args);
  const { transition } = body ?? {};

  if (!transition || (transition !== 'enter' && transition !== 'exit')) {
    homey.app.error('[api:postGeofenceEvent] Invalid or missing transition parameter:', transition);
    throw Object.assign(new Error('Invalid or missing transition parameter. Must be "enter" or "exit".'), { statusCode: 400 });
  }

  const cardId = transition === 'enter' ? 'geofence_enter' : 'geofence_exit';
  homey.app.log(`[api:postGeofenceEvent] Geofence event received: '${transition}'. Triggering card '${cardId}'...`);

  try {
    const triggerCard = homey.flow.getTriggerCard(cardId);
    if (!triggerCard) {
      homey.app.error(`[api:postGeofenceEvent] Trigger card '${cardId}' not found.`);
      return { success: false, error: `Trigger card '${cardId}' not found.` };
    }

    await triggerCard.trigger();
    homey.app.log(`[api:postGeofenceEvent] Flow trigger card '${cardId}' fired successfully.`);
    return { success: true, triggered: cardId };
  } catch (err) {
    homey.app.error(`[api:postGeofenceEvent] Error triggering '${cardId}':`, err.message || err);
    throw Object.assign(new Error(`Failed to fire flow card: ${err.message || err}`), { statusCode: 500 });
  }
}

/**
 * Handles `GET /thermometers`.
 *
 * Enforces session token authorization, retrieves the thermometer classification configuration
 * (indoor, outdoor) and the list of available devices with temperature measurement capabilities,
 * filtering out any devices natively excluded from Homey climate (climate_exclude: true),
 * marked as hidden, or whose effective class is not among the allowed climate classes.
 *
 * @public
 * @async
 * @param {object} args - Request arguments provided by Homey Web API.
 * @param {import('homey').Homey} args.homey - The Homey application instance.
 * @returns {Promise<{config: Object.<string, string>, devices: Array<{id: string, name: string, zone: string}>, allowed_classes: string[]}>}
 * @throws {Error} If the request is unauthenticated or unauthorized (HTTP 401).
 * @example
 * // Request:
 * // GET https://{homeyId}.connect.athom.com/api/app/com.dimapp.aaos/thermometers?token=<sessionToken>
 * //
 * // Response:
 * // { "config": { "dev-1": "indoor", "dev-2": "outdoor" }, "devices": [...], "allowed_classes": ["sensor", "thermostat", "heater", "airconditioning"] }
 */
async function getThermometersConfig(args) {
  const { homey } = args;
  await homey.app.requireValidSessionToken(args);
  homey.app.log('[api:getThermometersConfig] Thermometer configuration requested');
  const config = homey.settings.get('thermometers_config') || {};
  const allowedClimateClasses = _getAllowedClimateClasses();

  let thermometerDevices = [];
  try {
    const localUrl = await homey.api.getLocalUrl();
    const token = await homey.api.getOwnerApiToken();
    const res = await fetch(`${localUrl}/api/manager/devices/device`, {
      headers: { 'Authorization': `Bearer ${token}` }
    });
    if (res.ok) {
      const allDevs = await res.json();
      for (const dev of Object.values(allDevs)) {
        const hasTemp = Array.isArray(dev.capabilities) && dev.capabilities.includes('measure_temperature');
        const isClimateExcluded = dev.settings && dev.settings.climate_exclude === true;
        const isHidden = dev.hidden === true;
        const effectiveClass = (dev.virtualClass || dev.class || '').toLowerCase();
        const isClimateClass = allowedClimateClasses.has(effectiveClass);

        if (hasTemp && !isClimateExcluded && !isHidden && isClimateClass) {
          thermometerDevices.push({
            id: dev.id,
            name: dev.name,
            zone: dev.zone
          });
        } else if (hasTemp && !isClimateClass) {
          if (typeof homey.app.debugLog === 'function') {
            homey.app.debugLog(
              'api:getThermometersConfig',
              `EXCLUDE '${dev.name}' from thermometers (class='${effectiveClass}' not in climate classes: ${Array.from(allowedClimateClasses).join(', ')})`
            );
          }
        }
      }
    }
  } catch (err) {
    homey.app.error('[api:getThermometersConfig] Failed to fetch thermometer devices:', err.message);
  }

  homey.app.log(`[api:getThermometersConfig] Returning ${Object.keys(config).length} configured entries, ${thermometerDevices.length} available devices, allowed classes: ${Array.from(allowedClimateClasses).join(', ')}.`);
  return {
    config,
    devices: thermometerDevices,
    allowed_classes: Array.from(allowedClimateClasses),
  };
}

const fs = require('fs');

const MAX_LOG_BACKUPS = 2; // index 0 (active), 1, 2

/**
 * Returns standardized log file name based on rotation index.
 *
 * @private
 * @param {number} index - Rotation index (0 for active, 1+ for backups).
 * @returns {string} The log filename.
 * @example
 * const name = _getLogFileName(0); // 'app_debug.log'
 */
function _getLogFileName(index) {
  return index === 0 ? 'app_debug.log' : `app_debug.${index}.log`;
}

/**
 * Formats bytes into human-readable string.
 *
 * @private
 * @param {number} bytes - Number of bytes.
 * @returns {string} Formatted string, e.g. '1.2 MB'.
 * @example
 * const str = _formatBytes(1048576); // '1.0 MB'
 */
function _formatBytes(bytes) {
  if (bytes === 0) return '0 B';
  const k = 1024;
  const sizes = ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(1)) + ' ' + sizes[i];
}

/**
 * Handles `GET /log/status`.
 *
 * Returns current logging status and list of stored log files.
 *
 * @public
 * @param {object} args - Request arguments.
 * @param {import('homey').Homey} args.homey - Homey app instance.
 * @returns {Promise<object>} Status object containing file list and debug flag.
 * @example
 * // GET /api/app/com.dimapp.aaos/log/status
 */
async function getLogStatus({ homey }) {
  try {
    const logManager = homey.app.getLogManager ? homey.app.getLogManager() : null;
    if (!logManager) {
      return { exists: false, files: [], totalSize: 0, debugEnabled: false };
    }

    const files = [];
    let totalSize = 0;

    for (let i = 0; i <= MAX_LOG_BACKUPS; i++) {
      const filePath = logManager.getLogFilePath(i);
      if (fs.existsSync(filePath)) {
        const stats = fs.statSync(filePath);
        files.push({
          index: i,
          name: _getLogFileName(i),
          path: filePath,
          size: stats.size,
          sizeFormatted: _formatBytes(stats.size),
          modified: stats.mtime.toISOString(),
          isCurrent: i === 0,
        });
        totalSize += stats.size;
      }
    }

    return {
      exists: files.length > 0,
      files: files,
      totalSize: totalSize,
      totalSizeFormatted: _formatBytes(totalSize),
      debugEnabled: logManager.isDebugEnabled(),
    };
  } catch (error) {
    homey.app.error('[api:getLogStatus] Error:', error.message || error);
    return { exists: false, error: error.message || error };
  }
}

/**
 * Handles `GET /log/download/:index`.
 *
 * Constructs and returns the direct local URL to download a diagnostic log file.
 *
 * @public
 * @param {object} args - Request arguments.
 * @param {import('homey').Homey} args.homey - Homey app instance.
 * @param {object} args.params - URL route parameters.
 * @param {string} args.params.index - File index to download.
 * @returns {Promise<string>} Direct download URL.
 * @throws {Error} If index is invalid or file does not exist.
 * @example
 * // GET /api/app/com.dimapp.aaos/log/download/0
 */
async function getLogDownloadFile({ homey, params }) {
  try {
    if (!params || typeof params.index === 'undefined' || !/^\d+$/.test(String(params.index))) {
      homey.app.error('[api:getLogDownloadFile] Security rejection: Invalid file index format.');
      throw Object.assign(new Error('Invalid file index. Expected an integer.'), { statusCode: 400 });
    }

    const index = parseInt(params.index, 10);
    if (index < 0 || index > MAX_LOG_BACKUPS) {
      homey.app.error(`[api:getLogDownloadFile] Security rejection: File index ${index} out of range (0-${MAX_LOG_BACKUPS}).`);
      throw Object.assign(new Error(`File index out of range (0-${MAX_LOG_BACKUPS}).`), { statusCode: 400 });
    }

    const logManager = homey.app.getLogManager ? homey.app.getLogManager() : null;
    if (!logManager) {
      throw Object.assign(new Error('LogManager is not initialized.'), { statusCode: 500 });
    }

    const filePath = logManager.getLogFilePath(index);
    const fileName = _getLogFileName(index);

    if (!fs.existsSync(filePath)) {
      throw Object.assign(new Error(`Log file not found: ${fileName}`), { statusCode: 404 });
    }

    const appId = homey.manifest ? homey.manifest.id : homey.app.id;
    const localAddress = await homey.cloud.getLocalAddress();
    const downloadUrl = `http://${localAddress}/app/${appId}/userdata/${fileName}`;

    homey.app.log(`[api:getLogDownloadFile] Generated download URL for ${fileName}`);
    return downloadUrl;
  } catch (error) {
    homey.app.error('[api:getLogDownloadFile] Error:', error.message || error);
    throw error;
  }
}

/**
 * Handles `DELETE /log/:index`.
 *
 * Deletes a specific log file by rotation index.
 *
 * @public
 * @param {object} args - Request arguments.
 * @param {import('homey').Homey} args.homey - Homey app instance.
 * @param {object} args.params - URL route parameters.
 * @param {string} args.params.index - File index to delete.
 * @returns {Promise<object>} Result object.
 * @example
 * // DELETE /api/app/com.dimapp.aaos/log/0
 */
async function deleteLogFile({ homey, params }) {
  try {
    if (params && params.index === 'all') {
      return deleteAllLogs({ homey });
    }

    if (!params || typeof params.index === 'undefined' || !/^\d+$/.test(String(params.index))) {
      homey.app.error('[api:deleteLogFile] Security rejection: Invalid file index format.');
      throw Object.assign(new Error('Invalid file index. Expected an integer or "all".'), { statusCode: 400 });
    }

    const index = parseInt(params.index, 10);
    if (index < 0 || index > MAX_LOG_BACKUPS) {
      homey.app.error(`[api:deleteLogFile] Security rejection: File index ${index} out of range (0-${MAX_LOG_BACKUPS}).`);
      throw Object.assign(new Error(`File index out of range (0-${MAX_LOG_BACKUPS}).`), { statusCode: 400 });
    }

    const logManager = homey.app.getLogManager ? homey.app.getLogManager() : null;
    if (!logManager) {
      throw Object.assign(new Error('LogManager is not initialized.'), { statusCode: 500 });
    }

    const filePath = logManager.getLogFilePath(index);
    const fileName = _getLogFileName(index);

    if (index === 0) logManager.clearWriteQueue();
    if (fs.existsSync(filePath)) {
      await fs.promises.unlink(filePath).catch(() => {});
    }

    homey.app.log(`[api:deleteLogFile] Deleted log file: ${fileName}`);
    return { success: true, deletedFile: fileName };
  } catch (error) {
    homey.app.error('[api:deleteLogFile] Error:', error.message || error);
    const statusCode = error.statusCode || 500;
    throw Object.assign(new Error(error.message || 'Failed to delete log file.'), { statusCode });
  }
}

/**
 * Handles `DELETE /log/all`.
 *
 * Clears and deletes all stored diagnostic log files.
 *
 * @public
 * @param {object} args - Request arguments.
 * @param {import('homey').Homey} args.homey - Homey app instance.
 * @returns {Promise<object>} Result object.
 * @example
 * // DELETE /api/app/com.dimapp.aaos/log/all
 */
async function deleteAllLogs({ homey }) {
  try {
    const logManager = homey.app.getLogManager ? homey.app.getLogManager() : null;
    if (!logManager) {
      throw Object.assign(new Error('LogManager is not initialized.'), { statusCode: 500 });
    }
    await logManager.clearLogs();
    homey.app.log('[api:deleteAllLogs] All diagnostic log files cleared.');
    return { success: true };
  } catch (error) {
    homey.app.error('[api:deleteAllLogs] Error:', error.message || error);
    const statusCode = error.statusCode || 500;
    throw Object.assign(new Error(error.message || 'Failed to clear all logs.'), { statusCode });
  }
}

